#!/usr/bin/env bash
#
# clone-sml-projects.sh
#
# Clones major open-source Standard ML projects organized by category.
# Run from the directory where you want the "sml-projects/" tree created.
#
# Usage:
#   chmod +x clone-sml-projects.sh
#   ./clone-sml-projects.sh [--shallow]
#
# Options:
#   --shallow    Use --depth 1 for faster, smaller clones
#
# Total disk estimate (full clones): ~15-25 GB
# Total disk estimate (shallow):     ~3-6 GB

set -euo pipefail

DEPTH_FLAG=""
if [[ "${1:-}" == "--shallow" ]]; then
    DEPTH_FLAG="--depth 1"
    echo ">>> Shallow clone mode enabled (--depth 1)"
fi

ROOT="sml-projects"
mkdir -p "$ROOT"
cd "$ROOT"

clone() {
    local dir="$1"
    local url="$2"
    local desc="$3"

    if [[ -d "$dir" ]]; then
        echo "  [skip] $dir already exists"
        return
    fi

    echo "  [clone] $dir — $desc"
    # shellcheck disable=SC2086
    git clone $DEPTH_FLAG "$url" "$dir" 2>&1 | tail -1 || {
        echo "  [FAIL] Could not clone $url"
    }
}

