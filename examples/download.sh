Here's what I found. Note that this is a somewhat niche query — most large SML projects support multiple compilers, and documenting which specifically use SML/NJ (vs. MLton or Poly/ML) as a primary build path takes some digging. Here are the major ones:

1. SML/NJ itself — The compiler is self-hosting and is by far the largest SML/NJ-compiled project. The source tree (including MLRISC, CML, eXene, ml-lex, ml-yacc, the smlnj-lib, etc.) is enormous. GitHub: smlnj/legacy and smlnj/smlnj.

2. Manticore — A parallel ML compiler from UChicago (John Reppy's group). Implemented in a mix of C and SML code, requiring SML/NJ 110.81+ with MLRISC.
GitHub
SML/NJ is the primary build compiler. GitHub: ManticoreProject/manticore.

3. Twelf — The LF logical framework from CMU (Frank Pfenning). Can be compiled with SML/NJ (make smlnj) or MLton (make mlton).
GitHub
It has been used for large formalizations including a proof of safety for Standard ML and foundational typed assembly language systems.
Wikipedia
GitHub: standardml/twelf.

4. TILT Compiler — Robert Harper's certifying SML compiler based on typed intermediate languages. tilt-nj is a version of the compiler compiled by SML/NJ, and it compiles under SML/NJ version 110.0.7.
GitHub
GitHub: RobertHarper/TILT-Compiler.

5. Diderot — A domain-specific language for image analysis and visualization, also from UChicago (Reppy, Kindlmann, et al.). The compiler diderotc is a shell script containing absolute paths to the sml installation and to an architecture-specific binary file used by sml to compile Diderot.
GitHub
The compiler is written in SML and built with SML/NJ. GitHub: Diderot-Language/diderot.

6. Isabelle (historically) — The major theorem prover is written in SML and was historically compiled with SML/NJ. However, in February 2016, support for SML/NJ was removed from the Isabelle code base
Sketis
, and it now uses only Poly/ML. Still worth knowing about as one of the largest SML codebases ever (hundreds of thousands of lines).

7. MLton (bootstrap) — MLton is a whole-program optimizing SML compiler that is itself over 190K lines of SML. It can be bootstrapped from SML/NJ, though it primarily compiles itself. It supports CM files partly for SML/NJ interop.

8. Celf — An implementation of the Concurrent LF type theory (related to Twelf). Celf is written in Standard ML and compiles with MLton, MLKit, and SML/NJ.
Springer

A few caveats for your transpiler work: many of these projects use SML/NJ-specific extensions (higher-order functors, OR-patterns, quote/antiquote, CML, continuations, MLRISC integration) that go beyond standard SML '97 and would require extra attention during conversion. The ones most tightly coupled to SML/NJ are Manticore, Diderot, and SML/NJ itself, since they come from the same UChicago/Bell Labs lineage and lean heavily on CM, MLRISC, and CML.

